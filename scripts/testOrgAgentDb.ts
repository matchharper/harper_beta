async function testRequestMigration(sql: Db, notices: string[]) {
  notices.length = 0;
  await expectDbError(
    "request conflict migration",
    () => applyMigration(sql, MIGRATIONS[0]),
    /conflicting legacy\/internal values/i
  );
  assert(
    notices.some(
      (notice) =>
        notice.includes("legacy_only=3") &&
        notice.includes("internal_only=2") &&
        notice.includes("conflicts=1")
    ),
    "migration preflight did not report all request reconciliation sets"
  );
  assert(
    notices.some(
      (notice) =>
        notice.includes("excluded_external_requests=1") &&
        notice.includes("external_extensions_to_remove=1") &&
        notice.includes("target_over_20000=1") &&
        notice.includes("target_max_length=20001")
    ),
    "migration preflight did not report external and length risk counts"
  );
  const rollbackCheck = firstRow(
    await sql`
    select
      role.request as legacy,
      internal_role.request as internal,
      to_regprocedure('public.sync_legacy_company_role_request_to_internal_v1()') as bridge
    from public.company_roles role
    join public.company_internal_roles internal_role on internal_role.role_id = role.role_id
    where role.role_id = ${IDS.conflictRole}::uuid
  `
  );
  assert(
    rollbackCheck.legacy === "legacy conflict",
    "failed migration changed the legacy request"
  );
  assert(
    rollbackCheck.internal === "internal conflict",
    "failed migration changed the internal request"
  );
  assert(
    rollbackCheck.bridge === null,
    "failed migration leaked the compatibility trigger function"
  );
  logPass("request conflict abort is transactional");

  await sql`
    update public.company_internal_roles
    set request = 'legacy conflict'
    where role_id = ${IDS.conflictRole}::uuid
  `;
  notices.length = 0;
  await applyMigration(sql, MIGRATIONS[0]);
  assert(
    notices.some(
      (notice) =>
        notice.includes("legacy_only=3") &&
        notice.includes("internal_only=2") &&
        notice.includes("conflicts=0")
    ),
    "successful migration preflight did not report reconciled request counts"
  );

  const rows = await sql`
    select
      role.role_id,
      role.request as legacy,
      internal_role.request as internal
    from public.company_roles role
    left join public.company_internal_roles internal_role on internal_role.role_id = role.role_id
    order by role.role_id
  `;
  const byRole = new Map(rows.map((row) => [String(row.role_id), row]));
  assert(
    byRole.get(IDS.legacyRole)?.internal === "legacy request",
    "legacy request was not backfilled"
  );
  assert(
    byRole.get(IDS.missingExtensionRole)?.internal === "create extension",
    "missing internal extension was not created"
  );
  assert(
    byRole.get(IDS.internalOnlyRole)?.legacy === "internal-only request",
    "internal-only request was not mirrored to legacy"
  );
  assert(
    byRole.get(IDS.externalRole)?.legacy === "external request" &&
      byRole.get(IDS.externalRole)?.internal === null,
    "external-only extension request was not preserved on the parent before cleanup"
  );
  assert(
    String(byRole.get(IDS.oversizedRole)?.legacy).length === 20_001 &&
      byRole.get(IDS.oversizedRole)?.internal ===
        byRole.get(IDS.oversizedRole)?.legacy,
    "oversized legacy request was not preserved and mirrored byte-for-byte"
  );
  logPass(
    "request backfill preserves legacy readers and excludes external roles"
  );

  await sql`
    update public.company_roles
    set request = 'old writer update'
    where role_id = ${IDS.legacyRole}::uuid
  `;
  const bridged = firstRow(
    await sql`
    select request from public.company_internal_roles
    where role_id = ${IDS.legacyRole}::uuid
  `
  );
  assert(
    bridged.request === "old writer update",
    "rolling legacy writer bridge did not sync"
  );

  await sql`
    update public.company_roles
    set source_type = 'external'
    where role_id = ${IDS.legacyRole}::uuid
  `;
  const externalized = firstRow(
    await sql`
    select role.request,
           exists (
             select 1 from public.company_internal_roles internal_role
             where internal_role.role_id = role.role_id
           ) as has_extension
    from public.company_roles role
    where role.role_id = ${IDS.legacyRole}::uuid
  `
  );
  assert(
    externalized.request === "old writer update" &&
      externalized.has_extension === false,
    "rolling bridge did not preserve the parent request and remove the external extension"
  );

  await sql`
    update public.company_roles
    set source_type = 'internal', request = 'old writer returned internal'
    where role_id = ${IDS.legacyRole}::uuid
  `;
  const internalized = firstRow(
    await sql`
    select role.request as legacy_request, internal_role.request as internal_request
    from public.company_roles role
    join public.company_internal_roles internal_role on internal_role.role_id = role.role_id
    where role.role_id = ${IDS.legacyRole}::uuid
  `
  );
  assert(
    internalized.legacy_request === "old writer returned internal" &&
      internalized.internal_request === "old writer returned internal",
    "rolling bridge did not recreate the extension on external to internal transition"
  );
  await expectDbError(
    "external role extension scope",
    () => sql`
      insert into public.company_internal_roles(role_id, request)
      values (${IDS.externalRole}::uuid, 'must not persist')
    `,
    /only available for internal roles/i
  );
  logPass(
    "rolling legacy bridge syncs requests and preserves extension scope across source transitions"
  );
}

