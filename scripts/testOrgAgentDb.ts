function fail(message: string): never {
  throw new Error(`[org-agent-db] ${message}`);
}

function assert(condition: unknown, message: string): asserts condition {
  if (!condition) fail(message);
}

function value<T>(rows: readonly Record<string, unknown>[], key: string): T {
  assert(rows.length === 1, `expected one row while reading ${key}`);
  return rows[0]![key] as T;
}

async function expectDbError(
  label: string,
  operation: () => Promise<unknown>,
  pattern: RegExp
) {
  try {
    await operation();
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    assert(
      pattern.test(message),
      `${label} failed with an unexpected error: ${message}`
    );
    return;
  }
  fail(`${label} unexpectedly succeeded`);
}

function logPass(label: string) {
  process.stdout.write(`ok - ${label}\n`);
}

function isLoopback(hostname: string) {
  const normalized = hostname.replace(/^\[|\]$/g, "").toLowerCase();
  return (
    normalized === "localhost" ||
    normalized === "127.0.0.1" ||
    normalized === "::1"
  );
}

function parseStatusEnv(output: string) {
  for (const line of output.split(/\r?\n/)) {
    const match = line.match(/^DB_URL=(?:"([^"]+)"|'([^']+)'|(\S+))$/);
    if (match) return match[1] || match[2] || match[3] || null;
  }
  return null;
}

function discoverDatabaseUrl() {
  if (process.env.ORG_AGENT_TEST_DATABASE_URL) {
    return process.env.ORG_AGENT_TEST_DATABASE_URL;
  }
  try {
    const output = execFileSync(
      path.join(ROOT, "node_modules", ".bin", "supabase"),
      ["status", "--output", "env", "--workdir", ROOT],
      {
        cwd: ROOT,
        encoding: "utf8",
        env: { ...process.env, SUPABASE_TELEMETRY_DISABLED: "1" },
        stdio: ["ignore", "pipe", "pipe"],
      }
    );
    const discovered = parseStatusEnv(output);
    if (discovered) return discovered;
  } catch {
    // The actionable prerequisite error below is deliberately stable for CI.
  }
  fail(
    "No local Postgres is available. Start a Docker-compatible runtime, run " +
      "`pnpm exec supabase start`, or set ORG_AGENT_TEST_DATABASE_URL to a loopback Postgres URL."
  );
}

function guardDatabaseUrl(raw: string) {
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    fail("ORG_AGENT_TEST_DATABASE_URL is not a valid PostgreSQL URL");
  }
  assert(
    url.protocol === "postgres:" || url.protocol === "postgresql:",
    "ORG_AGENT_TEST_DATABASE_URL must use postgres:// or postgresql://"
  );
  assert(
    isLoopback(url.hostname),
    "refusing to run DB tests against a non-loopback host"
  );

  const protectedNames = [
    "DATABASE_URL",
    "POSTGRES_URL",
    "POSTGRES_URL_NON_POOLING",
    "POSTGRES_PRISMA_URL",
    "SUPABASE_DB_URL",
    "PRODUCTION_DATABASE_URL",
    "STAGING_DATABASE_URL",
  ];
  for (const name of protectedNames) {
    if (process.env[name] && process.env[name] === raw) {
      fail(
        `refusing to use ORG_AGENT_TEST_DATABASE_URL because it equals ${name}`
      );
    }
  }
  return url;
}

