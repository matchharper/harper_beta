async function testSlackReplyFinalization(sql: Db) {
  await ensureSlackFixtures(sql);

  const normalContent = "Normal Slack response";
  const normalMessageId = await insertNormalSlackAssistant(sql, {
    content: normalContent,
    jobId: IDS.normalReplyJob,
  });
  await sql`
    insert into public.slack_reply_jobs(
      id, slack_event_id, thread_id, response_message_id, trigger_kind,
      slack_message_ts, prompt, status, locked_at, locked_by, response_text
    ) values (
      ${IDS.normalReplyJob}::uuid, 'Ev_NORMAL', ${IDS.slackThread}::uuid,
      ${normalMessageId}, 'mention', '1700000010.000001', 'normal prompt',
      'processing', now(), 'db-test-worker', ${normalContent}
    )
  `;
  const normal = await finalizeSlackReply(sql, {
    jobId: IDS.normalReplyJob,
    slackMessageTs: "1700000011.000001",
  });
  assert(
    normal.status === "completed" &&
      normal.adopted === false &&
      Number(normal.response_message_id) === normalMessageId,
    "normal Slack reply was not finalized on its persisted assistant"
  );
  const normalState = firstRow(
    await sql`
    select job.status, job.response_message_id, job.slack_response_ts,
           job.completed_at, job.updated_at, job.locked_at, job.locked_by,
           message.slack_message_ts as message_ts,
           message.metadata,
           thread.created_by_harper
    from public.slack_reply_jobs job
    join public.company_messages message on message.id = job.response_message_id
    join public.company_slack_threads thread on thread.id = job.thread_id
    where job.id = ${IDS.normalReplyJob}::uuid
  `
  );
  assert(
    normalState.status === "completed" &&
      normalState.slack_response_ts === "1700000011.000001" &&
      normalState.message_ts === "1700000011.000001" &&
      normalState.created_by_harper === true &&
      normalState.locked_at === null &&
      normalState.locked_by === null,
    "normal Slack finalization did not atomically complete message, thread, and job"
  );
  const normalMetadata = normalState.metadata as Record<string, unknown>;
  assert(
    normalMetadata.source === "company_side_llm" &&
      normalMetadata.slackReplyJobId === IDS.normalReplyJob,
    "normal Slack finalization did not normalize company-side message metadata"
  );

  const repeated = await finalizeSlackReply(sql, {
    jobId: IDS.normalReplyJob,
    slackMessageTs: "1700000011.000001",
  });
  const repeatedState = firstRow(
    await sql`
    select completed_at, updated_at
    from public.slack_reply_jobs
    where id = ${IDS.normalReplyJob}::uuid
  `
  );
  assert(
    repeated.status === "completed" && repeated.idempotent === true,
    "Slack finalization retry was not idempotent"
  );
  assert(
    repeatedState.completed_at === normalState.completed_at &&
      repeatedState.updated_at === normalState.updated_at,
    "idempotent Slack finalization rewrote completion timestamps"
  );
  logPass("normal Slack reply finalization is atomic and idempotent");

  const adoptedContent = "Thread sync won this delivery race";
  const redundantMessageId = await insertNormalSlackAssistant(sql, {
    content: adoptedContent,
    jobId: IDS.adoptedReplyJob,
  });
  const canonicalMessageId = await insertNormalSlackAssistant(sql, {
    content: adoptedContent,
    jobId: "thread-sync-placeholder",
    slackMessageTs: "1700000021.000001",
    source: "slack_thread_sync",
  });
  await sql`
    update public.company_messages
    set model = null,
        thinking_logs = '[]'::jsonb,
        metadata = '{"source":"slack_thread_sync"}'::jsonb
    where id = ${canonicalMessageId}
  `;
  await sql`
    update public.company_conversations
    set last_message_id = ${redundantMessageId}
    where id = ${IDS.conversation}::uuid
  `;
  await sql`
    insert into public.slack_reply_jobs(
      id, slack_event_id, thread_id, response_message_id, trigger_kind,
      slack_message_ts, prompt, status, locked_at, locked_by, response_text
    ) values (
      ${IDS.adoptedReplyJob}::uuid, 'Ev_ADOPT', ${IDS.slackThread}::uuid,
      ${redundantMessageId}, 'mention', '1700000020.000001', 'adopt prompt',
      'processing', now(), 'db-test-worker', ${adoptedContent}
    )
  `;
  const adopted = await finalizeSlackReply(sql, {
    jobId: IDS.adoptedReplyJob,
    slackMessageTs: "1700000021.000001",
  });
  assert(
    adopted.status === "completed" &&
      adopted.adopted === true &&
      Number(adopted.response_message_id) === canonicalMessageId,
    "thread-sync winner was not adopted as the canonical Slack message"
  );
  const adoptedState = firstRow(
    await sql`
    select job.response_message_id,
           conversation.last_message_id,
           canonical.metadata,
           canonical.model,
           canonical.thinking_logs,
           exists(
             select 1 from public.company_messages redundant
             where redundant.id = ${redundantMessageId}
           ) as redundant_exists
    from public.slack_reply_jobs job
    join public.company_messages canonical on canonical.id = job.response_message_id
    join public.company_conversations conversation
      on conversation.id = canonical.conversation_id
    where job.id = ${IDS.adoptedReplyJob}::uuid
  `
  );
  const adoptedMetadata = adoptedState.metadata as Record<string, unknown>;
  assert(
    Number(adoptedState.response_message_id) === canonicalMessageId &&
      Number(adoptedState.last_message_id) === canonicalMessageId &&
      adoptedState.redundant_exists === false,
    "adopted Slack reply did not repoint job/conversation and delete redundant A"
  );
  assert(
    adoptedMetadata.slackReplyJobId === IDS.adoptedReplyJob &&
      adoptedMetadata.source === "company_side_llm" &&
      adoptedState.model === "test-slack-model" &&
      Array.isArray(adoptedState.thinking_logs) &&
      adoptedState.thinking_logs.length === 1,
    "adopted Slack row lost the normal assistant metadata"
  );
  logPass(
    "exact thread-sync winner is adopted without losing assistant metadata"
  );

  const conflictContent = "Expected Slack response";
  const conflictingAssistantId = await insertNormalSlackAssistant(sql, {
    content: conflictContent,
    jobId: IDS.conflictingReplyJob,
  });
  await insertNormalSlackAssistant(sql, {
    content: "Different Slack content",
    jobId: "thread-sync-conflict",
    slackMessageTs: "1700000031.000001",
    source: "slack_thread_sync",
  });
  await sql`
    insert into public.slack_reply_jobs(
      id, slack_event_id, thread_id, response_message_id, trigger_kind,
      slack_message_ts, prompt, status, locked_at, locked_by, response_text
    ) values (
      ${IDS.conflictingReplyJob}::uuid, 'Ev_CONFLICT', ${IDS.slackThread}::uuid,
      ${conflictingAssistantId}, 'mention', '1700000030.000001',
      'conflict prompt', 'processing', now(), 'db-test-worker', ${conflictContent}
    )
  `;
  await expectDbError(
    "Slack delivery content conflict",
    () =>
      finalizeSlackReply(sql, {
        jobId: IDS.conflictingReplyJob,
        slackMessageTs: "1700000031.000001",
      }),
    /Slack reply delivery conflict: existing Slack timestamp has different content or ownership/i
  );
  const conflictState = firstRow(
    await sql`
    select job.status, job.slack_response_ts,
           assistant.slack_message_ts as assistant_ts
    from public.slack_reply_jobs job
    join public.company_messages assistant on assistant.id = job.response_message_id
    where job.id = ${IDS.conflictingReplyJob}::uuid
  `
  );
  assert(
    conflictState.status === "processing" &&
      conflictState.slack_response_ts === null &&
      conflictState.assistant_ts === null,
    "delivery conflict partially completed the job or assistant"
  );
  logPass(
    "mismatched thread-sync delivery aborts with no partial finalization"
  );
}

