import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";

test("Gmail retries share a claim, preserve private Memory and fence replaced attempts and connections", async () => {
  const db = new PGlite();
  const owner = "00000000-0000-4000-8000-000000000001";
  const other = "00000000-0000-4000-8000-000000000002";
  const version = "2026-11-16T00:00:00Z";
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role;
      create table logs(id bigint generated by default as identity primary key, user_id uuid, type text, created_at timestamptz default now(), meta_data jsonb);
      create table talent_integrations(talent_id uuid, provider text, status text, updated_at timestamptz);
      create table saved(talent_id uuid, body text);
      create function mutate_talent_contexts(p_talent_id uuid,p_changes jsonb,p_request_id text) returns jsonb language plpgsql as $$
      begin insert into saved values(p_talent_id,p_changes->0->>'content'); return jsonb_build_object('applied',p_changes); end $$;
    `);
    await db.exec(
      readFileSync(
        new URL(
          "../../../supabase/migrations/20261116064407_career_gmail_history_claim.sql",
          import.meta.url
        ),
        "utf8"
      )
    );
    for (const id of [owner, other]) {
      await db.query(
        "insert into talent_integrations values($1,'gmail','active',$2)",
        [id, version]
      );
    }
    const claim = async (
      initial = false,
      talentId = owner,
      connection = version
    ) =>
      (
        await db.query<{
          result: { id: number; created: boolean; status: string };
        }>("select claim_gmail_history_run_v1($1,$2,$3) result", [
          talentId,
          connection,
          initial,
        ])
      ).rows[0].result;
    const advance = async (id: number, status: string, attempt: number) =>
      (
        await db.query<{ ok: boolean }>(
          "select advance_gmail_history_run_v1($1,$2,$3,$4,null) ok",
          [owner, id, status, attempt]
        )
      ).rows[0].ok;
    const save = (
      id: number,
      attempt: number,
      content: string,
      connection = version,
      talentId = owner
    ) =>
      db.query("select apply_gmail_history_memories_v1($1,$2,$3,$4,'req',$5)", [
        talentId,
        id,
        attempt,
        connection,
        JSON.stringify([{ content }]),
      ]);
    const [first, second] = await Promise.all([claim(true), claim(true)]);
    assert.equal(first.id, second.id);
    assert.notEqual(first.created, second.created);
    assert.equal(await advance(first.id, "failed", 0), true); // enqueue failure
    const recovered = await claim(true);
    assert.notEqual(recovered.id, first.id);
    assert.equal(await advance(recovered.id, "running", 1), true);
    assert.equal(await advance(recovered.id, "running", 1), false);
    assert.equal(await advance(recovered.id, "retrying", 1), true);
    assert.equal(await advance(recovered.id, "running", 2), true);
    await assert.rejects(save(recovered.id, 1, "old attempt"), /superseded/);
    await assert.rejects(
      save(recovered.id, 2, "wrong owner", version, other),
      /superseded/
    );
    await db.query(
      "update logs set meta_data=jsonb_set(meta_data,'{updatedAt}',to_jsonb(now()-interval '11 minutes')) where id=$1",
      [recovered.id]
    );
    const replacement = await claim(true);
    assert.equal(replacement.created, true);
    assert.equal(await advance(replacement.id, "running", 1), true);
    await save(replacement.id, 1, "Company corrected an earlier rejection");
    await assert.rejects(save(recovered.id, 2, "rejected"), /superseded/);
    assert.equal(await advance(recovered.id, "completed", 2), false);
    const newVersion = "2026-11-16T03:00:00Z";
    await db.query(
      "update talent_integrations set updated_at=$1 where talent_id=$2",
      [newVersion, owner]
    );
    await assert.rejects(
      save(replacement.id, 1, "old connection"),
      /superseded/
    );
    await assert.rejects(
      save(replacement.id, 1, "borrowed version", newVersion),
      /superseded/
    );
    const reconnect = await claim(true, owner, newVersion);
    await advance(reconnect.id, "running", 1);
    await advance(reconnect.id, "completed", 1);
    assert.equal((await claim(true, owner, newVersion)).id, reconnect.id);
    assert.equal(await advance(reconnect.id, "running", 2), false);
    assert.equal((await claim(false, owner, newVersion)).created, true);
    assert.notEqual((await claim(true, other)).id, reconnect.id);
    assert.deepEqual((await db.query("select body from saved")).rows, [
      { body: "Company corrected an earlier rejection" },
    ]);
  } finally {
    await db.close();
  }
});
