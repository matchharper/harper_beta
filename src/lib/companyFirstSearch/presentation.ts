/** Shared structural contract for company-visible reports, not a fit judge. */
function text(value: unknown) { return typeof value === "string" ? value.trim() : ""; }
function record(value: unknown): Record<string, any> {
  return value && typeof value === "object" && !Array.isArray(value) ? value as Record<string, any> : {};
}

export function parseCompanyCandidatePresentation(value: unknown, criteria: Array<{name: string; criteria?: string}>) {
  const raw = record(value);
  const introduction = text(raw.introduction);
  const names = new Set(criteria.map(item => item.name));
  if (!introduction || introduction.length > 1200 || !Array.isArray(raw.criteriaEvaluations)) {
    throw new Error("companyPresentation requires a compact introduction and criteriaEvaluations array");
  }
  const seen = new Set<string>();
  const criteriaEvaluations = raw.criteriaEvaluations.map((value: unknown) => {
    const item = record(value);
    const name = text(item.name), content = text(item.content);
    const fitness = text(item.fitness);
    if (!names.has(name) || seen.has(name) || !content || content.length > 1800 ||
        !["excellent", "good", "uncertain", "bad"].includes(fitness)) {
      throw new Error("Invalid or duplicate company criterion; use the current supplied criteria exactly once");
    }
    seen.add(name);
    return { name, content, fitness: fitness as "excellent" | "good" | "uncertain" | "bad",
      criterionDefinition: criteria.find(item => item.name === name)?.criteria ?? "" };
  });
  if (seen.size !== names.size) throw new Error("Every current company criterion requires an evaluation");
  return { introduction, criteriaEvaluations };
}

export const CHANGED_CRITERION_NOTE = "기준이 바뀌어 아직 다시 보지 않았어요";

/** Never label an assessment of old criteria as an assessment of the current ones.
 * Definitions are stamped from the input by code, never generated by the model.
 * Judged per current criterion: a grade made for the same definition is kept
 * (relabelled if only the name changed); any other current criterion reads as
 * not yet checked; grades for criteria no longer listed are dropped. */
export function currentCompanyCriteriaEvaluations(value: unknown, criteria: Array<{name: string; criteria?: string}>) {
  if (!Array.isArray(value) || !value.length || !criteria.length) return [];
  const entries = value.map(record);
  const used = new Set<number>();
  const take = (match: (item: Record<string, any>) => boolean) => {
    const index = entries.findIndex((item, at) => !used.has(at) && match(item));
    if (index < 0) return null;
    used.add(index);
    return entries[index];
  };
  const names = new Set(criteria.map(item => item.name));
  return criteria.map(criterion => {
    const definition = criterion.criteria ?? "";
    const kept = take(item => item.name === criterion.name && item.criterionDefinition === definition) ??
      (definition ? take(item => !names.has(item.name) && item.criterionDefinition === definition) : null);
    return kept
      ? { ...kept, name: criterion.name }
      : { name: criterion.name, fitness: "uncertain", content: CHANGED_CRITERION_NOTE, criterionDefinition: definition };
  });
}

/** A placeholder ("not checked yet") or still-pending cell is no grade: it is read again and never hides a real one. */
export function isGradedCriterion(evaluation: { content?: unknown; pending?: unknown }) {
  return evaluation.pending !== true && Boolean(evaluation.content) && evaluation.content !== CHANGED_CRITERION_NOTE;
}

/** A re-read still pending this long after its row was written was interrupted. */
const STALE_REREAD_MS = 5 * 60_000;

/** Pending cells of a re-read row older than 5 minutes read as not checked (no endless spinner). */
export function settleStaleRereads(value: unknown, updatedAt: string | null | undefined, now = Date.now()) {
  if (!Array.isArray(value) || !updatedAt || now - Date.parse(updatedAt) <= STALE_REREAD_MS) return value;
  return value.map(entry => {
    const item = record(entry);
    return item.pending === true ? { ...item, pending: false, fitness: "uncertain", content: CHANGED_CRITERION_NOTE } : entry;
  });
}
