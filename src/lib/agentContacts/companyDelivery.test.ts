import assert from "node:assert/strict";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { executeCompanyCorrespondence } from "./companyTools";
import type { Database } from "@/lib/career/matching/internalScoring/database";

const workspace = "00000000-0000-4000-8000-000000000001";
const role = "00000000-0000-4000-8000-000000000002";
const member = "00000000-0000-4000-8000-000000000003";
const ids = [4, 5, 6, 7, 8].map(n => `00000000-0000-4000-8000-${String(n).padStart(12, "0")}`);

async function fixture() {
  const pg = new PGlite();
  await pg.exec(`
    create table company_roles(role_id uuid, company_workspace_id uuid);
    create table company_internal_roles(role_id uuid, team_id uuid);
    create table company_user_workspace(id uuid, company_workspace_id uuid, company_user_id uuid, authority text, access_scope text, team_id uuid);
    create table company_workspace_team_members(membership_id uuid, team_id uuid);
    create table company_conversations(id uuid default gen_random_uuid(),company_workspace_id uuid,role_id uuid,metadata jsonb,unique(company_workspace_id,role_id));
    create table company_messages(id bigint generated by default as identity,company_workspace_id uuid,conversation_id uuid,role_id uuid,company_user_id uuid,role text,content text,message_type text,status text,model text,metadata jsonb);
    create table company_slack_channels(id uuid,company_workspace_id uuid,slack_channel_id text,is_enabled boolean);
    create table company_role_notification_channels(role_id uuid,channel_id uuid);
    insert into company_roles values('${role}','${workspace}');
    insert into company_internal_roles values('${role}',null);
    insert into company_user_workspace values('${member}','${workspace}','${member}','owner','organization',null);
    insert into company_messages(company_workspace_id,company_user_id,role,content) values('${workspace}','${member}','user','Notify our team');
    insert into company_slack_channels values
      ('${ids[0]}','${workspace}','C_ON_A',true),
      ('${ids[1]}','${workspace}','C_OPT_OUT',true),
      ('${ids[2]}','${workspace}','C_ON_B',true),
      ('${ids[3]}','${workspace}','C_DENIED',true),
      ('${ids[4]}','${workspace}','C_DISABLED',false);
    insert into company_role_notification_channels values('${role}','${ids[1]}');
  `);
  const database: Database = {
    query: async (sql, params) => (await pg.query(sql, params)).rows as any[],
    transaction: async work => pg.transaction(tx => work(async (sql, params) => (await tx.query(sql, params)).rows as any[])),
  };
  const checks: string[] = [];
  const batches: string[] = [];
  let fail = false;
  const delivery = {
    allowed: async ({ channelId }: { channelId: string }) => { checks.push(channelId); return channelId !== "C_DENIED"; },
    deliver: async (args: { batchId: string; assertCanStart: () => Promise<void> }) => {
      await args.assertCanStart();
      batches.push(args.batchId);
      if (fail) { fail = false; throw Error("delivery interrupted"); }
      return [];
    },
  };
  const run = (channel = "slack") => executeCompanyCorrespondence({
    source: { kind: "company", workspaceId: workspace, userId: member, messageId: 1 },
    name: "contact_user", input: { roleId: role, channel, body: "Candidate shared their profile." },
    sourceMessageId: 1, conversationId: "unused",
  }, database, delivery);
  return { pg, database, checks, batches, run, failNext: () => { fail = true; } };
}

test("contact_user commits all configured, permitted Slack destinations in one reusable batch", async () => {
  const f = await fixture();
  try {
    f.failNext();
    await assert.rejects(f.run(), /delivery interrupted/);
    const saved = await f.database.query("select * from company_messages where role='assistant' order by id");
    assert.equal(saved[0].message_type, "chat");
    const copies = saved.filter(row => row.message_type === "slack");
    assert.deepEqual(copies.map(row => row.metadata.companyMessageBatch.channelDbId), [ids[0], ids[2]]);
    assert.deepEqual(f.checks, ["C_ON_A", "C_ON_B", "C_DENIED"]);
    assert.equal(copies[0].metadata.companyMessageBatch.batchId, copies[1].metadata.companyMessageBatch.batchId);
    for (let attempt = 0; attempt < 2; attempt++) {
      const result = await f.run();
      assert.ok("status" in result);
      assert.equal(result.status, "sent");
    }
    assert.equal((await f.database.query("select * from company_messages where role='assistant'")).length, 3);
    assert.equal(new Set(f.batches).size, 1);
  } finally { await f.pg.close(); }
});

test("contact_user refuses Slack when no configured destination is permitted", async () => {
  const f = await fixture();
  try {
    await f.database.query("insert into company_role_notification_channels values($1,$2),($1,$3)", [role, ids[0], ids[2]]);
    await assert.rejects(f.run(), /No enabled Role notification channel/);
    assert.equal((await f.database.query("select * from company_messages where role='assistant'")).length, 0);
    assert.deepEqual(f.batches, []);
  } finally { await f.pg.close(); }
});

test("chat automatically delivers to Slack and retries or a later Slack call reuse the same batch", async () => {
  const f = await fixture();
  try {
    f.failNext();
    await assert.rejects(f.run("chat"), /delivery interrupted/);
    const saved = await f.database.query("select * from company_messages where role='assistant' order by id");
    assert.deepEqual(saved.map(row => row.message_type), ["chat", "slack", "slack"]);
    assert.ok(saved.every(row => row.content === saved[0].content));
    assert.ok(saved.slice(1).every(row => row.metadata.companyEventUiDuplicateOf === saved[0].id));
    assert.deepEqual(saved.slice(1).map(row => row.metadata.companyMessageBatch.channelDbId), [ids[0], ids[2]]);
    for (const channel of ["chat", "slack", "chat"]) {
      const result = await f.run(channel);
      assert.ok("status" in result);
      assert.equal(result.status, "sent");
      assert.match(result.modelOutput, /saved in the company's Role chat and delivered/);
    }
    assert.equal((await f.database.query("select * from company_messages where role='assistant'")).length, 3);
    assert.equal(new Set(f.batches).size, 1);
  } finally { await f.pg.close(); }
});

test("chat saves on the web when all Slack destinations are disabled or denied", async () => {
  const f = await fixture();
  try {
    await f.database.query("insert into company_role_notification_channels values($1,$2),($1,$3)", [role, ids[0], ids[2]]);
    const result = await f.run("chat");
    assert.ok("status" in result);
    assert.equal(result.status, "saved");
    assert.match(result.modelOutput, /No Slack or email alert was sent/);
    assert.deepEqual(f.checks, ["C_DENIED"]);
    assert.deepEqual(f.batches, []);
    const [saved] = await f.database.query("select * from company_messages where role='assistant'");
    assert.equal(saved.message_type, "chat");
    assert.equal(saved.metadata.companyMessageBatch, undefined);
  } finally { await f.pg.close(); }
});

test("the old Slack operation key is reused when the same action is called through chat", async () => {
  const f = await fixture();
  try {
    await f.run("slack");
    // Existing releases saved Slack-only copies under a channel-specific key.
    await f.database.query("delete from company_messages where role='assistant' and message_type='chat'");
    await f.database.query("update company_messages set metadata=jsonb_set(metadata,'{agentContactDeliveryKey}',to_jsonb($1::text)) where role='assistant'", [`1:contact_user:${role}:slack`]);
    const result = await f.run("chat");
    assert.ok("status" in result);
    assert.equal(result.status, "sent");
    assert.equal((await f.database.query("select * from company_messages where role='assistant'")).length, 2);
    assert.equal(new Set(f.batches).size, 1);
  } finally { await f.pg.close(); }
});
