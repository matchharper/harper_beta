const scalar = async (db: PGlite, sql: string, args: unknown[] = []) => (await db.query<{ result: any }>(`select ${sql} as result`, args)).rows[0].result;
const ago = (db: PGlite, table: string, where: string, minutes: number, column = "created_at") =>
  db.query(`update ${table} set ${column} = now() - make_interval(mins => $1) where ${where}`, [minutes]);
type Chat = { talent?: string; conv?: string };
/** An application review form as suggest_form saves it: deferred, shown by a reply's marker. */
async function form(db: PGlite, minutesAgo: number, { talent = user, conv = conversation, payload = {} as Record<string, unknown> } = {}) {
  const row = await scalar(db, "write_career_form($1,$2,'create',null,null,null,$3,'',null)", [talent, conv, {
    kind: "form", title: "Company A · Backend Engineer", presentationDeferred: true, relatedRefs: [{ type: "role", id: role }],
    items: [
      { id: "salary", label: "Expected salary", type: "text", content: { value: "" }, required: true },
      { id: "start", label: "Earliest start date", type: "text", content: { value: "" } },
    ],
    ...payload,
  }]);
  await ago(db, "talent_messages", `id=${row.id}`, minutesAgo);
  return row as { id: number; payload: { formId: number; revision: number } };
}
/** Harper saves the next revision of the form with a new question, saved minutesAgo. */
async function revise(db: PGlite, formId: number, expectedRevision: number, minutesAgo: number) {
  await scalar(db, "write_career_form($1,$2,'update',$3,null,$4,$5,'',null)", [user, conversation, formId, expectedRevision, {
    kind: "form", presentationDeferred: true, relatedRefs: [{ type: "role", id: role }],
    items: [{ id: "visa", label: "Do you need visa sponsorship?", type: "select", content: { options: [{ id: "yes", label: "Yes" }, { id: "no", label: "No" }] } }],
  }]);
  await ago(db, "talent_messages", `payload->>'formId'='${formId}' and payload->>'revision'='${expectedRevision + 1}'`, minutesAgo);
}
/** A chat message; a Harper reply places the forms in `shows` with the marker line chat turns write. */
async function message(db: PGlite, from: "user" | "assistant", minutesAgo: number,
  { talent = user, conv = conversation, shows = [] as number[], content = "" }: Chat & { shows?: number[]; content?: string } = {}) {
  const text = content || (from === "user" ? "Please apply" : withFormMarkers("Here is the review", shows));
  const { rows: [row] } = await db.query<{ id: number }>(`insert into talent_messages(user_id,conversation_id,role,message_type,content,payload,created_at)
    values ($1,$2,$3,'chat',$4,'{}',now() - make_interval(mins => $5)) returning id`, [talent, conv, from, text, minutesAgo]);
  return row.id;
}
/** The candidate's visible chat displayed messageId, last at minutesAgo. */
async function viewed(db: PGlite, messageId: number, minutesAgo: number, { talent = user, conv = conversation }: Chat = {}) {
  await scalar(db, "mark_career_messages_seen_v1($1,$2,$3)", [talent, conv, messageId]);
  await ago(db, "career_conversation_seen", `conversation_id='${conv}'`, minutesAgo, "seen_at");
}
const page = (n: number) => id(100 + n);
const presence = (db: PGlite, pageId: string, closed: boolean, talent = user) =>
  scalar(db, "mark_career_page_presence_v1($1,$2,$3)", [talent, pageId, closed]);
/** Calls functions as PostgREST does: a scalar function returns its value, a set returns rows. */
const rpcClient = (db: PGlite) => ({
  rpc: async (name: string, args: Record<string, unknown>) => {
    const keys = Object.keys(args);
    const result = await db.query<Record<string, unknown>>(`select * from ${name}(${keys.map((key, index) => `${key} => $${index + 1}`).join(", ")})`, keys.map(key => args[key]));
    const scalar = result.fields.length === 1 && result.fields[0].name === name;
    return { data: scalar ? result.rows[0]?.[name] ?? null : result.rows, error: null };
  },
  // The skip check also reads recommendation settings; this candidate has none.
  from: () => ({ select: () => ({ eq: () => ({ maybeSingle: async () => ({ data: null, error: null }) }) }) }),
}) as any;
/** The skip check that run start and email send call. */
const skipCheck = (db: PGlite, run: any) => assertCareerSourceEventsCurrent({ admin: rpcClient(db), run });
const admit = (db: PGlite, published: unknown[] = []) => admitUnansweredCareerForms(rpcClient(db), async job => { published.push(job); });
const runs = async (db: PGlite) => (await db.query<any>("select * from opportunity_discovery_run where trigger='career_form_unanswered' order by created_at")).rows;
const current = (db: PGlite, run: any) => scalar(db, "career_unanswered_forms_current_v1($1,$2,$3)", [run.talent_id, run.conversation_id,
  run.trigger_payload.unansweredForms.map((item: any) => ({ formId: item.formId, revision: item.revision }))]);

/** The candidate asked, Harper showed one form, the candidate viewed it at viewedMinutesAgo and closed Harper. */
async function leftForm(db: PGlite, viewedMinutesAgo = 40) {
  const request = await message(db, "user", 70);
  const saved = await form(db, 60);
  const reply = await message(db, "assistant", 59, { shows: [saved.id] });
  await presence(db, page(1), false);
  await viewed(db, reply, viewedMinutesAgo);
  return { request, saved, reply };
}

test("a seen application form left unanswered after Harper closed wakes the agent once, and reopening Harper cancels it", async () => {
  const db = await setup();
  try {
    const { request, saved } = await leftForm(db);
    assert.deepEqual(await admit(db), { admitted: 0, deferred: 0 }, "the page is still open");
    await presence(db, page(1), true);
    const published: unknown[] = [];
    assert.deepEqual(await admit(db, published), { admitted: 1, deferred: 0 });
    const [run] = await runs(db);
    assert.equal(run.status, "handed_off");
    assert.equal(run.dedupe_key, `career-form-unanswered:${saved.id}:1`);
    assert.equal(run.trigger_payload.runContract, "career_agent_v1");
    assert.equal(run.trigger_payload.cadencePolicy.affectsBaseCadence, false);
    assert.equal(run.trigger_payload.agentInvocation.replyId, `background:${run.id}`);
    assert.equal(run.trigger_payload.agentInvocation.sourceMessageCursor, request);
    assert.deepEqual(published, [{ userId: user, conversationId: conversation, backgroundRunId: run.id, replyId: `background:${run.id}` }]);
    const [listed] = readUnansweredForms(run);
    assert.equal(listed.formId, saved.id);
    assert.equal(listed.revision, 1);
    assert.deepEqual(listed.form.items.map(item => item.label), ["Expected salary", "Earliest start date"]);
    assert.equal(new Date(run.trigger_payload.chatSeenAt).getTime(),
      new Date(await scalar(db, "(select seen_at from career_conversation_seen)")).getTime());
    assert.equal(await current(db, run), true);
    await skipCheck(db, run);

    assert.deepEqual(await admit(db), { admitted: 0, deferred: 0 }, "once per form revision");
    await presence(db, page(2), false);
    const [after] = await runs(db);
    assert.deepEqual([after.status, after.error_message], ["cancelled", "The candidate has Career open"]);
    assert.equal(await current(db, run), false, "Harper is open again");
    await assert.rejects(skipCheck(db, run), CareerSourceChangedError);
  } finally { await db.close(); }
});

test("the form waits 30 minutes after the candidate last viewed it, and only forms from the last day count", async () => {
  const db = await setup();
  try {
    const { reply } = await leftForm(db, 10);
    await presence(db, page(1), true);
    assert.deepEqual(await admit(db), { admitted: 0, deferred: 0 }, "viewed 10 minutes ago");
    await viewed(db, reply, 31);
    assert.deepEqual(await admit(db), { admitted: 1, deferred: 0 });

    // Another candidate looks again at a form from a day and a half ago and leaves.
    await message(db, "user", 37 * 60, { talent: other, conv: otherConversation });
    const old = await form(db, 36 * 60, { talent: other, conv: otherConversation });
    const shown = await message(db, "assistant", 36 * 60, { talent: other, conv: otherConversation, shows: [old.id] });
    await presence(db, page(3), false, other);
    await viewed(db, shown, 40, { talent: other, conv: otherConversation });
    await presence(db, page(3), true, other);
    assert.deepEqual(await admit(db), { admitted: 0, deferred: 0 }, "the form is older than a day");
  } finally { await db.close(); }
});

test("a newer candidate message or an answer ends the reason to email", async () => {
  const db = await setup();
  try {
    const { saved } = await leftForm(db);
    await presence(db, page(1), true);
    const listed = [{ formId: saved.id, revision: 1 }];
    const isCurrent = (forms: unknown) => scalar(db, "career_unanswered_forms_current_v1($1,$2,$3)", [user, conversation, forms]);
    assert.equal(await isCurrent(listed), true);
    assert.equal(await isCurrent([...listed, { formId: saved.id + 1000, revision: 1 }]), false, "a listed form is not in this conversation");
    assert.equal(await isCurrent([]), false, "nothing listed");
    await message(db, "user", 35);
    assert.deepEqual(await admit(db), { admitted: 0, deferred: 0 }, "the candidate wrote after the form");
    assert.equal(await isCurrent(listed), false, "the candidate wrote, for example by replying to an earlier email");
  } finally { await db.close(); }
  const answered = await setup();
  try {
    const { saved } = await leftForm(answered);
    await presence(answered, page(1), true);
    assert.deepEqual(await admit(answered), { admitted: 1, deferred: 0 });
    const [run] = await runs(answered);
    await scalar(answered, "write_career_form($1,$2,'respond',$3,1,null,$4,'Approved',$5)",
      [user, conversation, saved.id, { values: { salary: "Negotiable", start: "Next month" } }, "answer-1"]);
    assert.equal(await current(answered, run), false, "answered in Career");
    await assert.rejects(skipCheck(answered, run), CareerSourceChangedError, "run start and email send skip it");
  } finally { await answered.close(); }
});

test("a form not shown in chat, or a reply the candidate has not seen, is left to the unseen-reply email", async () => {
  const db = await setup();
  try {
    // Held for a bundled review: the reply after it places other forms and names it only in passing.
    await message(db, "user", 70);
    const saved = await form(db, 60);
    const held = await message(db, "assistant", 58, { content: `The Company A review [[form:${saved.id}]] comes later.\n\n[[forms:[${saved.id * 10},${saved.id + 100}]]]` });
    await presence(db, page(1), false);
    await viewed(db, held, 55);
    await presence(db, page(1), true);
    assert.deepEqual(await admit(db), { admitted: 0, deferred: 0 }, "seen, but the form was not placed");
    // The reply that places it arrived after the candidate left.
    const shown = await message(db, "assistant", 50, { shows: [saved.id] });
    assert.deepEqual(await admit(db), { admitted: 0, deferred: 0 }, "an unseen reply");
    await presence(db, page(2), false);
    await viewed(db, shown, 40);
    await presence(db, page(2), true);
    assert.deepEqual(await admit(db), { admitted: 1, deferred: 0 }, "the candidate saw it placed and left");
  } finally { await db.close(); }
  const later = await setup();
  try {
    // The form was seen, but a newer Harper reply is still unseen.
    await leftForm(later);
    await message(later, "assistant", 45);
    await presence(later, page(1), true);
    assert.deepEqual(await admit(later), { admitted: 0, deferred: 0 });
  } finally { await later.close(); }
  const revised = await setup();
  try {
    // Harper revised the form after the candidate last looked, without placing it again.
    const { saved, reply } = await leftForm(revised, 45);
    await revise(revised, saved.id, 1, 40);
    await presence(revised, page(1), true);
    assert.deepEqual(await admit(revised), { admitted: 0, deferred: 0 }, "the new revision was saved after the last view");
    // The chat shows the newest revision where the reply placed the form.
    await presence(revised, page(2), false);
    await viewed(revised, reply, 35);
    await presence(revised, page(2), true);
    assert.deepEqual(await admit(revised), { admitted: 1, deferred: 0 });
    assert.deepEqual(readUnansweredForms((await runs(revised))[0]).map(item => [item.formId, item.revision]), [[saved.id, 2]]);
  } finally { await revised.close(); }
});

test("one email lists every waiting form of the conversation; a revision is listed once and a conversation gets one a day", async () => {
  const db = await setup();
  try {
    await message(db, "user", 80);
    const first = await form(db, 62);
    const second = await form(db, 61, { payload: { title: "Company B · Data Engineer", relatedRefs: [{ type: "opportunity", id: id(22) }] } });
    const suggestion = await form(db, 61, { payload: { kind: "suggestion", relatedRefs: [{ type: "role", id: role }], items: [{ id: "a", label: "Task", type: "action", content: {}, positive: { id: "go", label: "Go", message: "Go" } }] } });
    const plain = await form(db, 61, { payload: { relatedRefs: [] } });
    const reply = await message(db, "assistant", 60, { shows: [first.id, second.id, suggestion.id, plain.id] });
    await presence(db, page(1), false);
    await viewed(db, reply, 55);
    await presence(db, page(1), true);
    assert.deepEqual(await admit(db), { admitted: 1, deferred: 0 });
    const [run] = await runs(db);
    assert.deepEqual(readUnansweredForms(run).map(item => [item.formId, item.revision]), [[first.id, 1], [second.id, 1]],
      "application forms only: a suggestion and a form without a role or opportunity are not listed");
    assert.equal(run.dedupe_key, `career-form-unanswered:${second.id}:1`);

    // Harper revises the first form, and the candidate opens the chat again, sees it and leaves.
    await revise(db, first.id, 1, 50);
    await presence(db, page(2), false);
    await viewed(db, reply, 35);
    await presence(db, page(2), true);
    assert.equal(await current(db, run), false, "the listed revision changed");
    assert.deepEqual(await admit(db), { admitted: 0, deferred: 0 }, "one email a day per conversation");

    await db.query("update opportunity_discovery_run set created_at = now() - interval '25 hours'");
    assert.deepEqual(await admit(db), { admitted: 1, deferred: 0 });
    const [, next] = await runs(db);
    assert.deepEqual(readUnansweredForms(next).map(item => [item.formId, item.revision]), [[first.id, 2]],
      "the second form was already listed; only the new revision is");
    assert.equal(next.dedupe_key, `career-form-unanswered:${first.id}:2`);
    await db.query("update opportunity_discovery_run set created_at = now() - interval '25 hours'");
    assert.deepEqual(await admit(db), { admitted: 0, deferred: 0 }, "nothing new to list");
  } finally { await db.close(); }
});

test("test accounts, deleted accounts and another candidate's open page; only service_role can run the scan", async () => {
  const db = await setup();
  try {
    for (const [talent, conv] of [[tester, testerConversation], [other, otherConversation]]) {
      await message(db, "user", 70, { talent, conv });
      const saved = await form(db, 60, { talent, conv });
      const reply = await message(db, "assistant", 59, { talent, conv, shows: [saved.id] });
      await presence(db, page(talent === tester ? 4 : 5), false, talent);
      await viewed(db, reply, 40, { talent, conv });
      await presence(db, page(talent === tester ? 4 : 5), true, talent);
    }
    await db.query("update talent_users set deleted_at = now() where user_id = $1", [other]);
    assert.deepEqual(await admit(db), { admitted: 0, deferred: 0 });
    await db.query("update talent_users set deleted_at = null where user_id = $1", [other]);
    await presence(db, page(6), false);
    assert.equal(await presence(db, page(6), false, other), false, "a page id belongs to one candidate");
    assert.deepEqual(await admit(db), { admitted: 1, deferred: 0 });
    assert.equal((await runs(db))[0].talent_id, other);

    for (const signature of ["admit_career_unanswered_forms_v1(integer,integer,integer)", "career_unanswered_forms_current_v1(uuid,uuid,jsonb)",
      "career_reply_shows_form_v1(text,bigint)", "mark_career_page_presence_v1(uuid,uuid,boolean)"]) {
      for (const dbRole of ["anon", "authenticated"])
        assert.equal(await scalar(db, "has_function_privilege($1,$2,'EXECUTE')", [dbRole, signature]), false, `${dbRole} ${signature}`);
      assert.equal(await scalar(db, "has_function_privilege('service_role',$1,'EXECUTE')", [signature]), true, signature);
    }
  } finally { await db.close(); }
});

