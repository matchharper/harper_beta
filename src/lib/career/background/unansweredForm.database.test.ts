    assert.deepEqual(readUnansweredForms(run).map(item => [item.formId, item.revision]), [[first.id, 1], [second.id, 1]],
      "application forms only: a suggestion and a form without a role or opportunity are not listed");
    assert.equal(run.dedupe_key, `career-form-unanswered:${second.id}:1`);

