    await db.query("update opportunity_discovery_run set created_at = now() - interval '25 hours'");
    assert.deepEqual(await admit(db), { admitted: 1, deferred: 0 });
    const [, next] = await runs(db);
    assert.deepEqual(readUnansweredForms(next).map(item => [item.formId, item.revision]), [[first.id, 2]],
      "the second form was already listed; only the new revision is");
    assert.equal(next.dedupe_key, `career-form-unanswered:${first.id}:2`);
    await db.query("update opportunity_discovery_run set created_at = now() - interval '25 hours'");
