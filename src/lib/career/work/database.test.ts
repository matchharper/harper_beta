test("four inputs arriving during a running conversation share its inbox and checkpoint atomically", async () => {
  const db = await setup();
  try {
    const first = await admit(db, "first");
    const [{ id }] = await inbox(db);
    assert.equal((await claimInbox(db, id)).accepted, true);
    assert.equal(await saveInbox(db, id, [first.id]), true);
    const rest = await Promise.all(Array.from({ length: 4 }, (_, i) => admit(db, `next-${i}`)));
    const allIds = [first.id, ...rest.map(row => row.id)].sort((a, b) => a - b);
    assert.equal((await inbox(db)).length, 1);
    assert.deepEqual((await readInbox(db, id)).messages.map((row: any) => row.id), allIds.slice(1));
    assert.equal(await saveInbox(db, id, allIds, "stale-owner"), false);
    assert.deepEqual((await readInbox(db, id)).deliveredIds, [first.id]);
    assert.equal(await saveInbox(db, id, allIds), true);
    await assert.rejects(saveInbox(db, id, [first.id]), /cannot move backwards/);
    await assert.rejects(saveInbox(db, id, [...allIds, 999999]), /does not belong/);
    assert.equal(await scalar(db, "hide_career_work_source($1,$2,$3)", [user, conversation, rest[3].id]), true);
    await scalar(db, "release_career_agent_turn($1,$2,$3,'owner')", [user, conversation, `invocation:${id}`]);
    const resumed = await claimInbox(db, id);
    assert.deepEqual(resumed.state.checkpoint.inputMessageIds, allIds);
    assert.equal((await readInbox(db, id)).messages.length, 0);
    await assert.rejects(finishInbox(db, id), /has not completed/);
    assert.equal(await deliverInbox(db, id), true);
    assert.equal(await finishInbox(db, id), null);
    assert.equal((await inbox(db)).length, 0);
  } finally { await db.close(); }
});

