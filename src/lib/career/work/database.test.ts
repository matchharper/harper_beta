test("Stop retires active and checkpointed background runs without changing unrelated or finished runs", async () => {
  const db = await setup();
  try {
    const active = await backgroundRun(db), waiting = await backgroundRun(db);
    const unrelated = await backgroundRun(db), foreign = await backgroundRun(db, crypto.randomUUID(), other);
    const completed = await backgroundRun(db, crypto.randomUUID(), user, "completed");
    const state = { completedSequence: 5, handbooks: [{ id: "resume", remainingReplies: 2 }],
      activeReply: { replyId: `background:${active}`, claimId: "owner", expiresAt: new Date(Date.now() + 60_000).toISOString() },
      checkpoints: { [`background:${waiting}`]: { checkpointId: "saved" }, [`background:${foreign}`]: { checkpointId: "foreign" } } };
    await db.query("insert into talent_agent_runtime(user_id,conversation_id,state) values($1,$2,$3)", [user, conversation, state]);
    await assert.rejects(scalar(db, "stop_career_conversation($1,$2)", [other, conversation]), /unavailable/);
    await scalar(db, "stop_career_conversation($1,$2)", [user, conversation]);
    const rows = (await db.query<any>("select id,status,completed_at from opportunity_discovery_run")).rows;
    for (const id of [active, waiting]) {
      assert.equal(rows.find(r => r.id === id).status, "cancelled");
      assert.ok(rows.find(r => r.id === id).completed_at);
    }
    for (const id of [unrelated, foreign]) assert.equal(rows.find(r => r.id === id).status, "handed_off");
    assert.equal(rows.find(r => r.id === completed).status, "completed");
    const runtime = (await db.query<any>("select state from talent_agent_runtime")).rows[0].state;
    assert.deepEqual(runtime.handbooks, state.handbooks);
    assert.equal(runtime.completedSequence, 5);
    assert.equal(runtime.completedReplyIds[`background:${active}`], 5);
    const before = rows.find(r => r.id === active).completed_at;
    await scalar(db, "stop_career_conversation($1,$2)", [user, conversation]);
    assert.deepEqual((await db.query<any>("select completed_at from opportunity_discovery_run where id=$1", [active])).rows[0].completed_at, before);
  } finally { await db.close(); }
});

