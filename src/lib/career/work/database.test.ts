test("local and production inputs cannot merge, claim or recover each other's execution", async () => {
  const db = await setup();
  const environment = (name: string) => scalar(db, "set_config('request.headers',$1,false)", [JSON.stringify({ "x-harper-career-runtime": name })]);
  try {
    await environment("development:fixture");
    const local = await admit(db, "local");
    const [localJob] = await inbox(db);
    await environment("production");
    const production = await admit(db, "production");
    const jobs = await inbox(db);
    assert.equal(jobs.length, 2);
    const productionJob = jobs.find(job => job.id !== localJob.id)!;
    // Existing receipts have no environment stamp and remain production work.
    await db.query("update talent_external_operations set request=request-'execution_environment' where id=$1", [productionJob.id]);
    assert.deepEqual((await readInbox(db, productionJob.id)).messages.map((m: any) => m.id), [production.id]);
    assert.equal((await claimInbox(db, localJob.id)).accepted, false);
    const claims = (await db.query<any>("select * from claim_career_invocations(20,$1,$2)", [user, conversation])).rows;
    assert.deepEqual(claims.map(row => row.id), [productionJob.id]);
    await assert.rejects(scalar(db, "queue_career_invocation($1,$2,$3)", [user, conversation, local.id]), /environment mismatch/);
    await environment("development:fixture");
    assert.deepEqual((await readInbox(db, localJob.id)).messages.map((m: any) => m.id), [local.id]);
    assert.equal((await claimInbox(db, localJob.id)).accepted, true);
    const checkpoint = { executionEnvironment: "development:fixture", continuation: { channel: "career" }, replyId: "fixture" };
    await db.query("update talent_agent_runtime set state=$1", [{ checkpoints: { fixture: checkpoint } }]);
    await environment("production");
    assert.equal((await db.query("select * from claim_career_agent_checkpoint_recovery(20)")).rows.length, 0);
    await environment("development:fixture");
    assert.equal((await db.query("select * from claim_career_agent_checkpoint_recovery(20)")).rows.length, 1);
  } finally { await db.close(); }
});

