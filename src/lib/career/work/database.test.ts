test("cancelling a legacy pending reply fences recovery and preserves the current invocation", async () => {
  const db = await setup();
  try {
    const source = await admit(db, "legacy-source");
    await db.query("insert into talent_agent_runtime(conversation_id,user_id,state) values($1,$2,$3)", [conversation,user,{
      completedSequence: 2, activeReply:{replyId:"invocation:current",claimId:"current"},
      checkpoints:{legacy:{replyId:"legacy",checkpointId:"frozen",continuation:{sourceMessageId:source.id},waitFor:[{kind:"internal_evaluation",id:"private"}]},other:{replyId:"other",checkpointId:"other"}}
    }]);
    const cancel = (owner:string,key:string) => scalar(db,"cancel_career_pending_reply($1,$2,'legacy',$3)",[owner,conversation,key]);
    await assert.rejects(cancel(other,"frozen"),/Conversation unavailable/);
    await assert.rejects(cancel(user,"stale"),/Pending request changed/);
    assert.equal((await cancel(user,"frozen")).status,"cancelled");
    const state = (await db.query<any>("select state from talent_agent_runtime")).rows[0].state;
    assert.equal(state.activeReply.replyId,"invocation:current");
    assert.equal(state.checkpoints.legacy,undefined);
    assert.ok(state.checkpoints.other);
    assert.equal(state.completedReplyIds.legacy,2);
    assert.equal((await db.query<any>("select payload from talent_messages where id=$1",[source.id])).rows[0].payload.careerTurnStopped,true);
    assert.equal((await cancel(user,"frozen")).status,"already_completed");
    const cleanups = await db.query<any>("select request from talent_external_operations where request->>'cleanup'='true'");
    assert.deepEqual(cleanups.rows.map(r=>r.request.cancel_reply_ids),[["legacy"]]);
  } finally { await db.close(); }
});
