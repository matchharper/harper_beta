const scalar = async (db: PGlite, sql: string, args: unknown[] = []) => (await db.query<{ result: any }>(`select ${sql} as result`, args)).rows[0].result;
const admit = (db: PGlite, key: string, owner = user) => scalar(db, "admit_career_request($1,$2,'Please apply','chat',$3,null)", [owner, conversation, { clientRequestId: key }]);
const work = (db: PGlite, action: string, input: unknown) => scalar(db, "manage_career_work($1,$2,$3,$4)", [user, conversation, action, input]);
const form = (db: PGlite, action: string, input: unknown, id?: number, revision?: number, key?: string) => scalar(db,
  "write_career_form($1,$2,$3,$4,$5,null,$6,'',$7)", [user, conversation, action, id ?? null, revision ?? null, input, key ?? null]);
const inbox = async (db: PGlite) => (await db.query<{ id: string }>("select id from talent_external_operations where kind='career_invocation' and parent_id is null and status<>'completed' order by created_at,id")).rows;
const readInbox = (db: PGlite, id: string) => scalar(db, "read_career_inbox($1,$2,$3)", [user, conversation, id]);
const claimInbox = (db: PGlite, id: string, claim = "owner") => scalar(db, "claim_career_inbox($1,$2,$3,$4)", [user, conversation, id, claim]);
const saveInbox = (db: PGlite, id: string, ids: number[], claim = "owner") => scalar(db,
  "checkpoint_career_inbox($1,$2,$3,$4,$5)", [user, conversation, id, claim,
    { replyId: `invocation:${id}`, inputMessageIds: ids, messages: [{ role: "user", content: ids.join(" / ") }] }]);
const deliverInbox = (db: PGlite, id: string) => scalar(db, "finish_career_agent_turn($1,$2,$3,'owner','{}','[]')", [user, conversation, `invocation:${id}`]);
const finishInbox = (db: PGlite, id: string) => scalar(db, "finish_career_inbox($1,$2,$3)", [user, conversation, id]);

test("form groups commit one visible input, preserve each exact response and retry once", async () => {
  const db = await setup();
  try {
    const draft = { kind: "form", items: [{ id: "answer", label: "Answer", type: "text", content: "" }], presentationDeferred: true };
    const a = await form(db, "create", draft), b = await form(db, "create", draft);
    const responses = [a, b].map(row => ({ formId: row.id, revision: 1, values: { answer: `Answer ${row.id}` } }));
    const send = () => scalar(db, "respond_career_forms($1,$2,$3,$4,$5)", [user, conversation, "batch-1", responses, "Both answers"]);
    const message = await send();
    assert.equal((await send()).id, message.id);
    const rows = (await db.query<any>("select * from talent_messages where message_type='career_form_response' order by id")).rows;
    assert.equal(rows.length, 3);
    assert.equal(rows.filter(row => row.payload.hidden !== true).length, 1);
    assert.deepEqual(message.payload.responses.map((r: any) => [r.formId, r.revision, r.values, r.formSnapshot.items]), responses.map(r => [r.formId, 1, r.values, draft.items]));
    const jobs = await inbox(db);
    assert.equal(jobs.length, 1);
    assert.deepEqual((await readInbox(db, jobs[0].id)).messages.map((m: any) => m.id), [message.id]);
    for (const row of [a, b]) assert.equal(await scalar(db, "read_career_form_status($1,$2,$3,1)", [user, conversation, row.id]), "answered");
  } finally { await db.close(); }
});

test("a stale or stopped member rolls back the whole form group", async () => {
  const db = await setup();
  try {
    const a = await form(db, "create", { kind: "form", items: [] });
    const b = await form(db, "create", { kind: "form", items: [] });
    const responses = [a,b].map(row => ({ formId: row.id, revision: 1, values: {} }));
    await form(db, "resolve", {}, b.id, 1, "resolve-b");
    assert.equal(await scalar(db, "read_career_form_status($1,$2,$3,1)", [user, conversation, b.id]), "resolved");
    await assert.rejects(scalar(db, "respond_career_forms($1,$2,$3,$4,'Answers')", [user, conversation, "stale-batch", responses]), /changed or closed/);
    assert.equal((await db.query<any>("select count(*)::int n from talent_messages where message_type='career_form_response'")).rows[0].n, 0);
    assert.equal((await inbox(db)).length, 0);
    assert.equal(await scalar(db, "read_career_form_status($1,$2,$3,1)", [user, conversation, a.id]), "open");
    await assert.rejects(scalar(db, "respond_career_forms($1,$2,$3,$4,'Answers')", [other, conversation, "foreign", responses]), /unavailable/);
    await assert.rejects(scalar(db, "respond_career_forms($1,$2,$3,$4,'Answers')", [user, conversation, "duplicate", [responses[0], responses[0]]]), /Duplicate/);
  } finally { await db.close(); }
});

test("single and grouped submissions share one atomic answer boundary", async () => {
  const db = await setup();
  try {
    const a = await form(db, "create", { kind: "form", items: [] });
    const first = await form(db, "respond", { values: { answer: "saved" } }, a.id, 1, "single-1");
    assert.equal((await form(db, "respond", { values: {} }, a.id, 1, "single-1")).id, first.id);
    await assert.rejects(form(db, "respond", { values: { answer: "duplicate" } }, a.id, 1, "single-2"), /already answered/);
    const b = await form(db, "create", { kind: "form", items: [] });
    await assert.rejects(scalar(db, "respond_career_forms($1,$2,$3,$4,'Answers')", [user, conversation, "overlap", [b,a].map(row => ({ formId: row.id, revision: 1, values: {} }))]), /changed or closed/);
    assert.equal(await scalar(db, "read_career_form_status($1,$2,$3,1)", [user, conversation, b.id]), "open", "earlier batch children roll back too");
    await scalar(db, "respond_career_forms($1,$2,$3,$4,'Answers')", [user, conversation, "batch-only", [{ formId: b.id, revision: 1, values: {} }]]);
    await assert.rejects(form(db, "respond", { values: {} }, b.id, 1, "single-after-batch"), /already answered/);
    assert.equal((await db.query<any>("select count(*)::int n from talent_messages where message_type='career_form_response' and coalesce(payload->>'hidden','false')<>'true'")).rows[0].n, 2);
  } finally { await db.close(); }
});

