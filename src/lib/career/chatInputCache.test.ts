import assert from "node:assert/strict";
import test from "node:test";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
import { readCareerChatInputs } from "./chatInputCache.server";
import { projectCareerConversationHistory } from "@/lib/talentOnboarding/conversationSummary";

const migration = "supabase/migrations/20261111095048_career_chat_input_reuse_and_completion.sql";
test("session snapshots reuse account rows and history; edits, deletions, summaries and late IDs invalidate correctly", async () => {
  const db = new PGlite();
  const user = crypto.randomUUID(), other = crypto.randomUUID(), conversation = crypto.randomUUID();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role;
      alter default privileges grant execute on functions to anon,authenticated,service_role;
      create table talent_conversations(id uuid primary key,user_id uuid,stage text,updated_at timestamptz);
      create table talent_setting(user_id uuid primary key,preferred_locale text);
      create table talent_integrations(talent_id uuid,provider text,status text,primary key(talent_id,provider));
      create table talent_messages(id bigint primary key,user_id uuid,conversation_id uuid,role text,content text,message_type text,payload jsonb,created_at timestamptz default now());
      create table talent_conversation_summaries(id uuid primary key,talent_id uuid,conversation_id uuid,to_message_id bigint,segment_summary text,summary_text text,created_at timestamptz default now());`);
    await db.exec(await readFile(migration, "utf8"));
    await db.exec(await readFile("supabase/migrations/20261111095851_career_chat_completion_trace_reuse.sql", "utf8"));
    await db.query("insert into talent_conversations(id,user_id) values($1,$2)", [conversation,user]);
    await db.query("insert into talent_setting(user_id,preferred_locale) values($1,'ko')", [user]);
    const insert = (id: number, content: string, role = "assistant") => db.query("insert into talent_messages(id,user_id,conversation_id,role,content,message_type,payload) values($1,$2,$3,$4,$5,'chat','{}')",[id,user,conversation,role,content]);
    await insert(1,"Earlier");
    const replies: any[] = [];
    const admin: any = { rpc: async (name: string, args: any) => {
      assert.equal(name,"read_career_chat_inputs");
      const result = (await db.query<any>("select read_career_chat_inputs($1,$2,$3,null,$4) as data",[args.p_user_id,args.p_conversation_id,args.p_cached,args.p_history])).rows[0];
      replies.push(result.data); return { data: result.data, error: null };
    } };
    const read = (history = true) => readCareerChatInputs({ admin,userId:user,conversationId:conversation,history });
    const first = await read();
    assert.equal(first.setting?.preferred_locale,"ko");
    assert.equal(first.gmail,null);
    first.messages[0].content = "Caller mutation";
    await insert(2,"New reply");
    const second = await read();
    assert.deepEqual(second.messages.map(row=>row.content),["Earlier","New reply"]);
    assert.equal(replies.at(-1).resetHistory,false);
    assert.equal(replies.at(-1).messages.length,1);
    assert.ok(!Object.hasOwn(replies.at(-1),"setting"));
    assert.ok(!Object.hasOwn(replies.at(-1),"gmail"));
    await db.query("update talent_setting set preferred_locale='en' where user_id=$1",[user]);
    await db.query("insert into talent_integrations(talent_id,provider,status) values($1,'gmail','active')",[user]);
    const changed = await read(false);
    assert.equal(changed.setting?.preferred_locale,"en");
    assert.equal(changed.gmail?.status,"active");
    assert.deepEqual(changed.messages,second.messages);
    await db.query("update talent_messages set role='user' where id=1");
    await read();
    await db.query(`update talent_messages set payload=payload||'{"careerCapabilityTurn":{"status":"completed"}}' where id=1`);
    await read();
    assert.equal(replies.at(-1).resetHistory,false,"runtime-only source trace is absent from model history");
    assert.equal(replies.at(-1).messages.length,0);
    await db.query("update talent_messages set content='Edited' where id=1");
    assert.equal((await read()).messages[0].content,"Edited");
    assert.equal(replies.at(-1).resetHistory,true);
    await db.query("delete from talent_messages where id=1");
    assert.deepEqual((await read()).messages.map(row=>row.id),[2]);
    await insert(5,"Higher ID"); await read(); await insert(4,"Late lower ID");
    assert.deepEqual((await read()).messages.map(row=>row.id),[2,4,5]);
    assert.equal(replies.at(-1).resetHistory,true);
    await db.query("insert into talent_conversation_summaries(id,talent_id,conversation_id,to_message_id,segment_summary,summary_text) values($1,$2,$3,4,'segment','Saved summary')",[crypto.randomUUID(),user,conversation]);
    const summarized = await read();
    assert.deepEqual(summarized.messages.map(row=>row.id),[5]);
    assert.equal(summarized.summary?.summary_text,"Saved summary");
    await insert(6,"Pending user", "user");
    const projected = projectCareerConversationHistory({ ...await read(),userId:user,conversationId:conversation,pendingUserMessageId:6 });
    assert.equal(projected.length,2);
    assert.equal(projected[0].message_type,"conversation_summary");
    assert.equal(projected[1].content,"Higher ID");
    await db.query("delete from talent_integrations where talent_id=$1",[user]);
    assert.equal((await read()).gmail,null);
    await assert.rejects(readCareerChatInputs({ admin,userId:other,conversationId:conversation }),/Conversation unavailable/);
    const exposed = await db.query<any>("select proname from pg_proc where proname in ('read_career_chat_inputs','read_career_inbox_context','finish_career_chat_execution','revise_career_history_read','revise_career_account_read') and (has_function_privilege('anon',oid,'execute') or has_function_privilege('authenticated',oid,'execute'))");
    assert.equal(exposed.rows.length,0);
  } finally { await db.close(); }
});
