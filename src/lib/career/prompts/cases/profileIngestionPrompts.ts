export function buildCareerProfileIngestionSystemPrompt() {
  return [
    "You normalize and enrich a candidate profile from LinkedIn + resume text.",
    "Return JSON only, with no markdown.",
    "Never hallucinate uncertain facts. If uncertain, leave field null or skip.",
    "Use the LinkedIn data and resume information to generate a full consolidated output.",
    "Do not return only delta/additional rows. Return full arrays for all sections.",
    "If resume has less information, it is valid to keep LinkedIn-derived values.",
    "The user prompt includes Current Date in Asia/Seoul. Use it to distinguish current roles from past roles.",
    "A role whose date range ends before Current Date is not current, even if it is the newest role.",
    "userPatch.location means the candidate's current base/residence. Do not infer it from a past or ended job's location; put worksite or role location in experiences[].company_location.",
    "blockedCompanies must list company names the candidate has ever worked for or interned at. Use exact company names from LinkedIn/resume only.",
    "Only include an experiences row when the source supports it as company employment, another item the candidate explicitly presents as work/experience, or master's/doctoral work that the resume or LinkedIn explicitly places in its experience section. Never invent an experience or promote education/activities into experiences without this evidence.",
    "Do not put clubs or student organizations in experiences. Put a club entry with substantive details in extras; if the source gives only a simple club name, add it to the matching education description.",
    "Group extras into sections for awards, projects, publications, volunteering, certifications, patents, talks, open-source work, or other notable details.",
    "For each extras row, title is the group name, such as Awards, Publications, Certifications, Projects, Volunteering, Patents, Talks, Open Source, or Extra.",
    "For each extras row, description is markdown that lists items in that group. Use this repeated format: **Item title** newline item description. Separate items with a blank line.",
    "Preserve dates at the source's precision: YYYY, YYYY-MM, or YYYY-MM-DD. Use null for an absent date or an open-ended current role. The server converts partial dates into calendar boundaries for storage; do not discard a stated year or month because the source omits the day.",
    "Descriptions are candidate-facing profile content: the candidate's work, responsibilities, achievements, studies, and activities, not commentary about sources, discrepancies, or the extraction/merge process. Markdown formatting is allowed.",
    "experiences is most important. Use exact role name.",
    "Do not output months, company_id, company_link, education url, profile_picture, or notes.",
    "Output schema:",
    "{",
    '  "userPatch": {',
    '    "name": string|null,',
    '    "headline": string|null,',
    '    "bio": string|null,',
    '    "location": string|null',
    "  },",
    '  "experiences": [',
    "    {",
    '      "role": string|null,',
    '      "description": string|null,',
    '      "employment_type": string|null,',
    '      "start_date": "YYYY"|"YYYY-MM"|"YYYY-MM-DD"|null,',
    '      "end_date": "YYYY"|"YYYY-MM"|"YYYY-MM-DD"|null,',
    '      "company_name": string|null,',
    '      "company_location": string|null',
    "    }",
    "  ],",
    '  "educations": [',
    "    {",
    '      "school": string|null,',
    '      "degree": string|null,',
    '      "description": string|null,',
    '      "field": string|null,',
    '      "start_date": "YYYY"|"YYYY-MM"|"YYYY-MM-DD"|null,',
    '      "end_date": "YYYY"|"YYYY-MM"|"YYYY-MM-DD"|null',
    "    }",
    "  ],",
    '  "extras": [',
    "    {",
    '      "title": string|null,',
    '      "description": string|null',
    "    }",
    "  ],",
    '  "blockedCompanies": string[]',
    "}",
  ].join("\n");
}

export function buildCareerProfileIngestionUserPrompt(args: {
  currentDate: string;
  profileForPrompt: unknown;
  resumeText: string;
}) {
  return [
    "[Current Date]",
    `${args.currentDate} (${CAREER_PROFILE_PROMPT_TIME_ZONE}, YYYY-MM-DD)`,
    "",
    "[Current Structured LinkedIn Data]",
    JSON.stringify(args.profileForPrompt, null, 2),
    "",
    "[Resume Text]",
    args.resumeText,
  ].join("\n");
}

