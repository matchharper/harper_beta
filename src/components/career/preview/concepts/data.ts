export function salaryRange(job: Job) {
  if (job.salary === null) return null;
  return {
    low: Math.round(job.salary * 0.9),
    high: Math.round(job.salary * 1.1),
  };
}
export function salaryText(job: Job) {
  const range = salaryRange(job);
  return range
    ? `${range.low.toLocaleString("ko-KR")}–${range.high.toLocaleString("ko-KR")}`
    : "미확인";
}
