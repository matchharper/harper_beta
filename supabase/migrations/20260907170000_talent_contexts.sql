create extension if not exists vector;

create table if not exists public.talent_contexts (
  id bigint generated by default as identity primary key,
  talent_id uuid not null references public.talent_users(user_id) on delete cascade,
  ref bigint not null,
  collection text not null,
  label text,
  key text,
  content text not null,
  source_refs jsonb not null default '[]'::jsonb,
  revision bigint not null default 1,
  embedding vector(1536),
  embedding_model text,
  embedding_content_hash text,
  embedding_updated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint talent_contexts_collection_check
    check (collection in ('brief', 'memory')),
  constraint talent_contexts_content_check
    check (length(btrim(content)) between 1 and 8000),
  constraint talent_contexts_label_check
    check (
      (collection = 'brief' and label is not null and length(btrim(label)) between 1 and 160)
      or (collection = 'memory' and label is null)
    ),
  constraint talent_contexts_key_check
    check (key is null or (collection = 'brief' and length(btrim(key)) between 1 and 160)),
  constraint talent_contexts_source_refs_check
    check (jsonb_typeof(source_refs) = 'array')
);

create unique index if not exists talent_contexts_active_key_uidx
  on public.talent_contexts (talent_id, key)
  where collection = 'brief' and key is not null and deleted_at is null;

create unique index if not exists talent_contexts_talent_ref_uidx
  on public.talent_contexts (talent_id, ref);

create index if not exists talent_contexts_active_collection_idx
  on public.talent_contexts (talent_id, collection, updated_at desc, id desc)
  where deleted_at is null;

create index if not exists talent_contexts_pending_embedding_idx
  on public.talent_contexts (updated_at, id)
  where collection = 'memory' and deleted_at is null and embedding is null;

alter table public.talent_contexts enable row level security;

